/* CVAT Face Landmark-50 — options page.
 *
 * Reads/writes the same `face50Cfg` record the content script uses, so there is
 * one source of truth. The labels JSON shown at the bottom is the packaged
 * `labels_raw.json` (generated from the fixed 50-point topology by
 * face50-server/tools/labels_spec.py).
 */

(() => {
  'use strict';

  const STORE_CFG = 'face50Cfg';

  const SCHEMA = [
    { name: 'longmaytrai', first: 0, count: 5, color: '#e11d48', closed: false },
    { name: 'longmayphai', first: 5, count: 5, color: '#f97316', closed: false },
    { name: 'songmui', first: 10, count: 4, color: '#eab308', closed: false },
    { name: 'mattrai', first: 14, count: 8, color: '#22c55e', closed: true },
    { name: 'matphai', first: 22, count: 8, color: '#14b8a6', closed: true },
    { name: 'moingoai', first: 30, count: 12, color: '#3b82f6', closed: true },
    { name: 'moitrong', first: 42, count: 8, color: '#a855f7', closed: true },
  ];

  const DEFAULTS = {
    endpoint: 'http://localhost:58219/predict',
    timeoutMs: 120000,
    replace: false,
    previewOnly: false,
    showIds: false,
    groups: Object.fromEntries(SCHEMA.map((s) => [s.name, true])),
  };

  const $ = (id) => document.getElementById(id);
  const ui = {
    endpoint: $('endpoint'),
    timeout: $('timeout'),
    test: $('test'),
    status: $('status'),
    replace: $('replace'),
    previewOnly: $('previewOnly'),
    showIds: $('showIds'),
    groups: $('groups'),
    copy: $('copy'),
    download: $('download'),
    labels: $('labels'),
    save: $('save'),
    reset: $('reset'),
    saveStatus: $('saveStatus'),
  };

  /* ---------------------------------------------------------------- *
   * Labels JSON (task setup)
   *
   * Packaged copy of face50-server/labels_raw.json, generated by
   * `python face50-server/tools/labels_spec.py --out ../face50-extension/labels_raw.json`.
   * Keeping one file avoids the extension and the setup script disagreeing.
   * ---------------------------------------------------------------- */

  const LABELS_FILE = 'labels_raw.json';
  let labelsText = '';

  async function loadLabelsFile() {
    try {
      const res = await fetch(chrome.runtime.getURL(LABELS_FILE), { cache: 'no-store' });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      labelsText = await res.text();
      JSON.parse(labelsText); // fail early on a broken package
    } catch (err) {
      labelsText = '';
      ui.labels.value = `Cannot read ${LABELS_FILE}: ${err.message}`;
      return;
    }
    ui.labels.value = labelsText;
  }

  function labelsJSON() {
    return labelsText;
  }

  /* ---------------------------------------------------------------- *
   * Config
   * ---------------------------------------------------------------- */

  function readForm() {
    const groups = {};
    for (const input of ui.groups.querySelectorAll('input[data-group]')) {
      groups[input.dataset.group] = input.checked;
    }
    return {
      endpoint: ui.endpoint.value.trim() || DEFAULTS.endpoint,
      timeoutMs: clampTimeout(ui.timeout.value),
      replace: ui.replace.checked,
      previewOnly: ui.previewOnly.checked,
      showIds: ui.showIds.checked,
      groups: { ...DEFAULTS.groups, ...groups },
    };
  }

  function clampTimeout(value) {
    const n = Number(value);
    if (!Number.isFinite(n)) return DEFAULTS.timeoutMs;
    return Math.min(600, Math.max(10, Math.round(n))) * 1000;
  }

  function fillForm(cfg) {
    ui.endpoint.value = cfg.endpoint;
    ui.timeout.value = String(Math.round(cfg.timeoutMs / 1000));
    ui.replace.checked = !!cfg.replace;
    ui.previewOnly.checked = !!cfg.previewOnly;
    ui.showIds.checked = !!cfg.showIds;
    for (const input of ui.groups.querySelectorAll('input[data-group]')) {
      input.checked = cfg.groups[input.dataset.group] !== false;
    }
  }

  function normalizeCfg(stored) {
    const cfg = { ...DEFAULTS, ...(stored || {}) };
    cfg.groups = { ...DEFAULTS.groups, ...((stored && stored.groups) || {}) };
    if (!Number.isFinite(cfg.timeoutMs)) cfg.timeoutMs = DEFAULTS.timeoutMs;
    return cfg;
  }

  async function load() {
    const data = await chrome.storage.local.get([STORE_CFG]);
    const cfg = normalizeCfg(data[STORE_CFG]);
    fillForm(cfg);
    await loadLabelsFile();
  }

  async function save() {
    const cfg = readForm();
    fillForm(cfg); // echo normalized values back
    await chrome.storage.local.set({ [STORE_CFG]: cfg });
    note(`Saved. Content-script panels pick this up on their next tick.`);
  }

  async function reset() {
    const cfg = normalizeCfg(DEFAULTS);
    fillForm(cfg);
    await chrome.storage.local.set({ [STORE_CFG]: cfg });
    note('Reset to defaults.');
  }

  /* ---------------------------------------------------------------- *
   * Actions
   * ---------------------------------------------------------------- */

  let noteTimer = 0;

  function note(text, kind = '') {
    ui.saveStatus.textContent = text;
    ui.saveStatus.className = `hint ${kind}`.trim();
    clearTimeout(noteTimer);
    noteTimer = setTimeout(() => {
      ui.saveStatus.textContent = '';
    }, 4000);
  }

  function setStatus(text, kind = '') {
    ui.status.textContent = text;
    ui.status.className = kind;
  }

  async function testConnection() {
    const endpoint = ui.endpoint.value.trim() || DEFAULTS.endpoint;
    setStatus('Testing…');
    ui.test.disabled = true;
    try {
      const res = await chrome.runtime.sendMessage({ type: 'face50-ping', endpoint });
      if (!res || !res.ok) throw new Error(res?.error || 'No response from the service worker.');
      const info = res.data || {};
      const backend = info.backend || info.model || 'unknown';
      const version = info.version ? ` v${info.version}` : '';
      setStatus(`OK — backend ${backend}${version}`, 'ok');
    } catch (err) {
      setStatus(err?.message || String(err), 'err');
    } finally {
      ui.test.disabled = false;
    }
  }

  async function copyLabels() {
    const text = labelsJSON();
    if (!text) {
      note('Labels JSON is not available — reinstall the extension.', 'err');
      return;
    }
    try {
      await navigator.clipboard.writeText(text);
      note('Labels JSON copied.');
    } catch {
      ui.labels.focus();
      ui.labels.select();
      const ok = document.execCommand('copy');
      note(ok ? 'Labels JSON copied.' : 'Copy failed — select the text and copy manually.', ok ? '' : 'err');
    }
  }

  function downloadLabels() {
    if (!labelsText) {
      note('Labels JSON is not available — reinstall the extension.', 'err');
      return;
    }
    const blob = new Blob([labelsJSON()], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'labels_raw.json';
    a.click();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
    note('Downloaded labels_raw.json.');
  }

  /* ---------------------------------------------------------------- *
   * Wiring
   * ---------------------------------------------------------------- */

  function buildGroupInputs() {
    for (const group of SCHEMA) {
      const label = document.createElement('label');
      label.className = 'inline';
      const input = document.createElement('input');
      input.type = 'checkbox';
      input.dataset.group = group.name;
      input.id = `group-${group.name}`;
      input.addEventListener('change', () => save().catch((e) => note(e.message, 'err')));
      const text = document.createElement('span');
      text.textContent = `${group.name} (${group.first}–${group.first + group.count - 1})`;
      label.append(input, text);
      ui.groups.append(label);
    }
  }

  buildGroupInputs();

  ui.test.addEventListener('click', testConnection);
  ui.copy.addEventListener('click', copyLabels);
  ui.download.addEventListener('click', downloadLabels);
  ui.save.addEventListener('click', () => save().catch((e) => note(e.message, 'err')));
  ui.reset.addEventListener('click', () => reset().catch((e) => note(e.message, 'err')));

  for (const el of [ui.replace, ui.previewOnly, ui.showIds]) {
    el.addEventListener('change', () => save().catch((e) => note(e.message, 'err')));
  }

  load().catch((e) => note(`Cannot load settings: ${e.message}`, 'err'));
})();
